#!/bin/bash
#
# verify.sh - AI 응답 검증 스킬 (읽기 전용)
#
# AI가 준 답변의 정확성, 안전성, 완결성을 검증
# 수정 권한 없이 리뷰만 수행
#
# Usage:
#   /verify "AI 응답"          # 정확성, 안전성, 완결성 검증
#   /verify --code "코드"      # 코드 구현 검증
#   /verify --duo "내용"       # 다중 AI 검증
#

cat << 'VERIFY_EOF'
---
allowed-tools: Read, Grep, Glob, Bash, WebFetch, WebSearch, LSP
description: AI 응답 검증 - 정확성/안전성/완결성 (읽기 전용, 수정 없음)
---

Args: "$ARGUMENTS"

## ⚠️ 중요: 읽기 전용 모드

이 스킬은 **검증만 수행**하며, **절대 코드를 수정하지 않습니다**.
- ✅ Read, Grep, Glob, Bash (읽기), LSP (분석)
- ❌ Edit, Write (수정 금지)

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
🔍 /verify 사용 가이드

용도: AI 응답의 정확성, 안전성, 완결성 검증

사용법:
  /verify "AI가 준 답변"         # 전체 검증
  /verify --code "코드+설명"    # 구현 검증
  /verify --safety "내용"       # 보안 검증
  /verify --logic "주장"        # 논리 검증
  /verify --duo "내용"          # 다중 AI 교차 검증

검증 카테고리:
  accuracy    정확성 (사실 확인, 논리 오류, 모순)
  safety      안전성 (보안 취약점, 위험 코드)
  completeness 완결성 (누락, 에지 케이스)
  feasibility 실행성 (실제 동작 여부)

옵션:
  --code       코드 구현 검증
  --safety     보안만 집중 검증
  --logic      논리/주장 검증
  --duo        Claude + Gemini 교차 검증
  --help       이 도움말

예시:
  /verify "이 코드로 로그인 기능 구현하라고 했어"
  /verify --code "AI가 작성한 인증 코드 검증"
  /verify --safety "이 SQL 쿼리 안전한지?"
  /verify --duo "이 답변이 정확한지 검증"

언제 사용:
  ✅ AI 답변을 받은 후 검증
  ✅ 구현 코드가 맞는지 확인
  ✅ 보안 취약점 확인
  ✅ 논리적 모순 확인

특징:
  ⭐ 읽기 전용 (절대 수정 안 함)
  ⭐ 4가지 검증 카테고리
  ⭐ 교차 검증 (--duo)
