## 1. Parse Options

### 검증 유형 (기본: 전체)
- `--code` - 코드 구현 검증
- `--safety` - 보안만 집중
- `--logic` - 논리/주장 검증
- (없음) - 전체 검증

### 협업 모드
- `--duo` - Claude + Gemini 교차 검증

## 2. Verification Categories

### Accuracy (정확성)
- 사실 확인 (기술적 정확성)
- 논리 오류 감지
- 모순 확인 (전후 맥락)
- 참조 검증 (API, 문서)

### Safety (안전성)
- 보안 취약점 (OWASP Top 10)
- 위험 코드 패턴
- Hardcoded secrets
- Injection 위험

### Completeness (완결성)
- 누락된 부분
- 에지 케이스 처리
- 에러 핸들링
- 필수 검증

### Feasibility (실행성)
- 실제 동작 여부
- 의존성 확인
- 환경 제약 사항

