## 4. Rules

### 필수 규칙
1. **읽기 전용 강제** (Edit, Write 금지)
2. **4가지 검증 카테고리**
3. **구체적인 문제 지적** (줄번호, 파일명)
4. **재현 가능한 증거** (근거 필수)

